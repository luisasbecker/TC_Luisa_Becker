def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_ppm(path: Path) -> tuple[int, int, bytes]:
    raw = path.read_bytes()
    match = re.match(rb"P6\s+(\d+)\s+(\d+)\s+255\s", raw)
    if not match:
        raise ValueError(f"Expected 8-bit RGB P6 output from pdfimages: {path}")
    width, height = (int(value) for value in match.groups())
    pixels = raw[match.end():]
    if len(pixels) != width * height * 3:
        raise ValueError(f"Unexpected PPM data size: {path}")
    return width, height, pixels


def crop_rgb(image: tuple[int, int, bytes], box: tuple[int, int, int, int]):
    width, height, pixels = image
    x0, y0, x1, y1 = box
    if not (0 <= x0 < x1 <= width and 0 <= y0 < y1 <= height):
        raise ValueError(f"Out-of-bounds crop: {box} / {width}x{height}")
    rows = [pixels[(y * width + x0) * 3:(y * width + x1) * 3] for y in range(y0, y1)]
    return x1 - x0, y1 - y0, b"".join(rows)


def encode_png(image: tuple[int, int, bytes]) -> bytes:
    width, height, pixels = image
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    rows = b"".join(b"\0" + pixels[y * width * 3:(y + 1) * width * 3] for y in range(height))
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(rows, 9))
        + chunk(b"IEND", b"")
    )


def decode_generated_png(data: bytes) -> tuple[int, int, bytes]:
    """Independently check dimensions, chunk integrity and every stored RGB pixel."""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("Invalid PNG signature")
    offset, compressed, size = 8, bytearray(), None
    while offset < len(data):
        length = struct.unpack(">I", data[offset:offset + 4])[0]
        kind = data[offset + 4:offset + 8]
        payload = data[offset + 8:offset + 8 + length]
        checksum = struct.unpack(">I", data[offset + 8 + length:offset + 12 + length])[0]
        if checksum != zlib.crc32(kind + payload):
            raise ValueError("Invalid PNG chunk checksum")
        if kind == b"IHDR":
            width, height, depth, color, compression, filtering, interlace = struct.unpack(">IIBBBBB", payload)
            if (depth, color, compression, filtering, interlace) != (8, 2, 0, 0, 0):
                raise ValueError("Unexpected PNG format")
            size = width, height
        elif kind == b"IDAT":
            compressed.extend(payload)
        elif kind == b"IEND":
            break
        offset += length + 12
    if size is None:
        raise ValueError("Missing PNG dimensions")
    width, height = size
    raw = zlib.decompress(compressed)
    stride = width * 3 + 1
    if len(raw) != stride * height or any(raw[y * stride] != 0 for y in range(height)):
        raise ValueError("Unexpected PNG scanline encoding")
    pixels = b"".join(raw[y * stride + 1:(y + 1) * stride] for y in range(height))
    return width, height, pixels


def save_unchanged_or_new(path: Path, data: bytes, verify_only: bool):
    if path.exists():
        if path.read_bytes() != data:
            raise RuntimeError(f"Refusing to overwrite a different existing file: {path}")
    elif verify_only:
        raise RuntimeError(f"Missing generated file: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def rectangle(box):
    x0, y0, x1, y1 = box
    return {
        "coordinate_system": "native_image_pixels_top_left_origin",
        "x": x0, "y": y0, "width": x1 - x0, "height": y1 - y0,
        "right_exclusive": x1, "bottom_exclusive": y1,
    }


