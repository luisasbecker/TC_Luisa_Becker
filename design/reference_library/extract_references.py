def make_contact_sheet(images, target: Path):
    """Native-size comparison sheet; labels are bitmap glyphs, never inside assets."""
    # Only the short labels C0-A ... C5-A, Q-A and Q-B need these glyphs.
    glyphs = {
        "C": ["0111", "1000", "1000", "1000", "1000", "1000", "0111"],
        "Q": ["0110", "1001", "1001", "1001", "1011", "1001", "0111"],
        "A": ["0110", "1001", "1001", "1111", "1001", "1001", "1001"],
        "B": ["1110", "1001", "1001", "1110", "1001", "1001", "1110"],
        "0": ["0110", "1001", "1001", "1001", "1001", "1001", "0110"],
        "1": ["0010", "0110", "0010", "0010", "0010", "0010", "0111"],
        "2": ["0110", "1001", "0001", "0010", "0100", "1000", "1111"],
        "3": ["1110", "0001", "0001", "0110", "0001", "0001", "1110"],
        "4": ["1001", "1001", "1001", "1111", "0001", "0001", "0001"],
        "5": ["1111", "1000", "1000", "1110", "0001", "0001", "1110"],
        "-": ["0000", "0000", "0000", "1111", "0000", "0000", "0000"],
    }
    width, height = 760, 760
    pixels = bytearray(bytes((244, 244, 244)) * width * height)
    for index, (label, image) in enumerate(images):
        if index < 9:
            x, y = 40 + (index % 3) * 240, 40 + (index // 3) * 120
        else:
            x, y = 40 + (index - 9) * 350, 420
        iw, ih, rgb = image
        for row in range(ih):
            start = ((y + row) * width + x) * 3
            pixels[start:start + iw * 3] = rgb[row * iw * 3:(row + 1) * iw * 3]
        for pos, char in enumerate(label):
            for gy, line in enumerate(glyphs[char]):
                for gx, value in enumerate(line):
                    if value == "1":
                        for dy in range(2):
                            for dx in range(2):
                                loc = ((y - 20 + gy * 2 + dy) * width + x + pos * 12 + gx * 2 + dx) * 3
                                pixels[loc:loc + 3] = b"\x20\x20\x20"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(encode_png((width, height, bytes(pixels))))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=ROOT.parents[2] / "TC2_Luisa" / "Referências")
    parser.add_argument("--verify", action="store_true", help="Verify existing outputs without creating them")
    parser.add_argument("--contact-sheet", type=Path, help="Optional temporary inspection PNG")
    args = parser.parse_args()
    pdfimages = shutil.which("pdfimages")
    if not pdfimages:
        raise SystemExit("Poppler pdfimages is required; no source files were changed.")
    for filename in [CLASSIFICATION_PDF, FOCUS_PDF]:
        if not (args.source_dir / filename).is_file():
            raise SystemExit(f"Missing source PDF: {args.source_dir / filename}")

    assets, previews = [], []
    source_metadata = sources(args.source_dir)
    with tempfile.TemporaryDirectory(prefix="tcc-reference-") as temp:
        temp = Path(temp)
        for filename, page, prefix in [(CLASSIFICATION_PDF, 4, "classes"), (FOCUS_PDF, 3, "focus")]:
            subprocess.run([pdfimages, "-f", str(page), "-l", str(page), str(args.source_dir / filename), str(temp / prefix)], check=True)
        subprocess.run([pdfimages, "-f", "4", "-l", "4", "-j", str(args.source_dir / CLASSIFICATION_PDF), str(temp / "context")], check=True)
        context_bytes = (temp / "context-000.jpg").read_bytes()
        context_file = "context/gomes_2023_figure_2_original.jpg"
        save_unchanged_or_new(ROOT / context_file, context_bytes, args.verify)
        figure = read_ppm(temp / "classes-000.ppm")
        if figure[:2] != (865, 720):
            raise ValueError("Source figure dimensions changed; review crop coordinates before extracting")
        context = {
            "file": context_file, "sha256": digest(context_bytes),
            "source_ref": "gomes_2023_elementary", "pdf_page": 4, "figure": "2",
            "width_px": figure[0], "height_px": figure[1],
            "native_rgb_sha256": digest(figure[2]),
            "kind": "original_composite_figure_with_schematic_drawings_and_clinical_photographs",
            "extraction": "Embedded JPEG copied without recompression by pdfimages -j; not a new clinical asset.",
        }
        for class_index, suffix, position, box in PANELS:
            image = crop_rgb(figure, box)
            data = encode_png(image)
            identifier = f"gomes2023_fig2_class{class_index}_{suffix}"
            path = f"photos/{identifier}.png"
            save_unchanged_or_new(ROOT / path, data, args.verify)
            if decode_generated_png((ROOT / path).read_bytes()) != image:
                raise ValueError(f"Native pixel verification failed: {identifier}")
            assets.append({
                "id": identifier, "file": path, "kind": "clinical_reference_photo",
                "lesion_class_index": class_index, "lesion_class_label": CLASS_NAMES[class_index],
                "source_ref": "gomes_2023_elementary",
                "source_location": {
                    "pdf_page": 4, "figure": "2", "category": class_index + 1,
                    "panel": f"Category {class_index + 1}, {position}",
                    "asset_suffix_note": "a/b are local left/right identifiers; these letters are not printed on the source photograph.",
                    "explicit_source_label": SOURCE_LABELS[class_index],
                    "class_assignment_basis": "Explicit printed category label; not inferred from photographic appearance.",
                    "context_file": context_file,
                },
                "crop": rectangle(box),
                "dimensions": {"width_px": image[0], "height_px": image[1]},
                "sha256": digest(data), "native_rgb_sha256": digest(image[2]),
                "source_figure_sha256": digest(context_bytes),
                "transforms": ["documented_panel_crop_at_native_resolution", "lossless_RGB_PNG_encoding"],
                "quality_limits": [
                    "Small photograph embedded in a published composite figure; original full-resolution clinical file was not supplied.",
                    "No resampling, sharpening, retouching, AI enhancement, or diagnostic annotation applied.",
                    "Narrow source padding retained around some photographs to avoid clipping; crop is a document panel extraction, not lesion segmentation.",
                    "Enlargement cannot recover additional clinical detail.",
                ],
                "eligibility": {"class_reference_gallery": True, "test_input": True, "quality_example": False},
                "risk_label": None, "risk_note": "The source supplies an elementary class, not a low/medium/high risk ground truth.",
                "attribution": f"Gomes et al. (2023), Figure 2, Category {class_index + 1}. DOI: 10.3390/ijerph20053894. CC BY 4.0. Photograph cropped from the original figure; native pixels preserved.",
            })
            previews.append((f"C{class_index}-{suffix.upper()}", image))

        for ordinal, panel, label, quality in [(0, "a", "sharp oral lesion image", "sharp"), (1, "b", "blurred one", "blurred")]:
            image = read_ppm(temp / f"focus-{ordinal:03}.ppm")
            expected = (305, 305) if ordinal == 0 else (307, 307)
            if image[:2] != expected:
                raise ValueError("Focus source dimensions changed; review figure mapping")
            data = encode_png(image)
            identifier = f"souza_focus_fig1_{panel}_{quality}"
            path = f"quality/{identifier}.png"
            save_unchanged_or_new(ROOT / path, data, args.verify)
            if decode_generated_png((ROOT / path).read_bytes()) != image:
                raise ValueError(f"Native pixel verification failed: {identifier}")
            assets.append({
                "id": identifier, "file": path, "kind": "clinical_quality_example",
                "lesion_class_index": None, "lesion_class_label": None,
                "source_ref": "souza_focus_supplied",
                "source_location": {"pdf_page": 3, "figure": "1", "panel": panel, "explicit_source_label": label},
                "source_quality_label": quality,
                "crop": rectangle((0, 0, image[0], image[1])),
                "dimensions": {"width_px": image[0], "height_px": image[1]},
                "sha256": digest(data), "native_rgb_sha256": digest(image[2]),
                "transforms": ["embedded_image_extraction_at_native_resolution", "lossless_RGB_PNG_encoding"],
                "quality_limits": [
                    "Quality label is taken from Figure 1's caption, not computed by the prototype.",
                    "No elementary lesion class or risk is assigned to this photograph.",
                    "No resampling, sharpening, retouching, AI enhancement, or diagnostic annotation applied.",
                ],
                "eligibility": {"class_reference_gallery": False, "test_input": True, "quality_example": True},
                "risk_label": None,
                "attribution": f"Souza et al., A method for focus analysis in images of oral lesions, Figure 1({panel}), supplied PDF p. 3. Publication year not identified in supplied file. Native embedded image extracted without retouching.",
            })
            previews.append((f"Q-{panel.upper()}", image))

    if len({item["id"] for item in assets}) != len(assets):
        raise ValueError("Duplicate asset identifiers")
    counts = {str(index): sum(item["lesion_class_index"] == index for item in assets) for index in range(6)}
    if list(counts.values()) != [2, 2, 2, 1, 1, 1]:
        raise ValueError("Unexpected class mapping")
    manifest = {
        "schema_version": 1,
        "purpose": "Local academic reference gallery and authorized test inputs; not training data or clinically validated predictions.",
        "source_permission": "User states permission for use of the supplied article images in this academic work, including reference display and pipeline/cloud tests. No upload is performed by this extraction script.",
        "mapping": {str(index): name for index, name in enumerate(CLASS_NAMES)},
        "summary": {"classified_photographs": 9, "quality_examples": 2, "photographs_by_class_index": counts},
        "sources": source_metadata,
        "context_figures": [context],
        "assets": assets,
        "verification": {
            "pixel_preservation": "Each PNG decoded and compared byte-for-byte with the corresponding source-native RGB crop.",
            "class_mapping": "Six printed source category labels reviewed; local class indexes 0-5 map to source categories 1-6.",
            "risk_assignment": "None; neither photographs nor elementary classes determine simulated risk.",
        },
    }
    data = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()
    save_unchanged_or_new(ROOT / "manifest.json", data, args.verify)
    if args.contact_sheet:
        make_contact_sheet(previews, args.contact_sheet)
    print(json.dumps({"verified_assets": len(assets), "class_counts": counts, "context_figures": 1, "verify_only": args.verify}, ensure_ascii=False))


if __name__ == "__main__":
    main()
